import Foundation

struct UpcomingDeparture: Equatable {
    let minutes: Int
    let time: String
}

struct MetroFacilities: Equatable {
    let entrances: [String]
    let pathways: [String: Int]
    let transfers: [String]
    let hasRestrooms: Bool
}

struct GTFSEntrance: Decodable, Sendable {
    let name: String
    let lat: Double
    let lon: Double
}

struct GTFSTransfer: Decodable, Sendable {
    let to: String
    let name: String
}

struct GTFSStationRecord: Decodable, Sendable {
    let name: String
    let lat: Double
    let lon: Double
    let lines: [String]
    let entrances: [GTFSEntrance]
    let pathways: [String: Int]
    let transfers: [GTFSTransfer]
    let restrooms: Bool
}

struct GTFSLineDirection: Decodable, Sendable {
    let headsign: String
    let departures: [String: [String: [Int]]]
}

private struct GTFSMetroPayload: Decodable {
    let stations: [String: GTFSStationRecord]
    let lines: [String: [String: GTFSLineDirection]]
}

/// Metrorex timetables and station facilities from the BUCHAREST-REGION GTFS feed
/// (bundled as `metro_gtfs.json`, generated by `build_metro_gtfs.py`).
struct MetroGTFSStore: Sendable {
    static let shared = MetroGTFSStore()

    static let pathwayLabels: [String: String] = [
        "elevator": "lifturi",
        "escalator": "scări rulante",
        "stairs": "scări",
        "walkway": "culoare",
        "moving_walkway": "trotuare rulante",
        "fare_gate": "porți",
        "exit_gate": "ieșiri"
    ]

    private let stations: [String: GTFSStationRecord]
    private let lines: [String: [String: GTFSLineDirection]]
    private let stationIdsByName: [String: [String]]

    private init() {
        var decoded: GTFSMetroPayload?
        if let url = LocalTransitDataManager.resolveResourceURL(name: "metro_gtfs", ext: "json"),
           let data = try? Data(contentsOf: url) {
            do {
                decoded = try JSONDecoder().decode(GTFSMetroPayload.self, from: data)
            } catch {
                print("MetroGTFSStore: decode failed: \(error)")
            }
        }
        let loadedStations = decoded?.stations ?? [:]
        stations = loadedStations
        lines = decoded?.lines ?? [:]

        var index: [String: [String]] = [:]
        for (id, record) in loadedStations {
            index[Self.normalize(record.name), default: []].append(id)
        }
        stationIdsByName = index
    }

    // MARK: - Public API

    /// Next departures for a metro line at a station, on the current service day (LV weekdays, SD weekends).
    /// Returns nil when the station can't be matched to GTFS.
    func upcomingDepartures(
        line: String,
        stationName: String,
        lat: Double,
        lon: Double,
        limit: Int,
        at date: Date = Date()
    ) -> [UpcomingDeparture]? {
        guard let sid = stationId(name: stationName, lat: lat, lon: lon) else { return nil }
        let calendar = Calendar.current
        let weekday = calendar.component(.weekday, from: date)
        let service = (weekday == 1 || weekday == 7) ? "SD" : "LV"
        let nowMinutes = calendar.component(.hour, from: date) * 60 + calendar.component(.minute, from: date)

        let times = Array((lines[line.uppercased()] ?? [:]).values)
            .flatMap { $0.departures[service]?[sid] ?? [] }
            .filter { $0 >= nowMinutes }
            .sorted()
            .prefix(limit)

        return times.map { UpcomingDeparture(minutes: $0 - nowMinutes, time: Self.clock($0)) }
    }

    /// Short label for a station row: "Acum", "În N min", or "Program încheiat". Nil when unmatched.
    func nextDepartureLabel(line: String, stationName: String, lat: Double, lon: Double, at date: Date = Date()) -> String? {
        guard let upcoming = upcomingDepartures(line: line, stationName: stationName, lat: lat, lon: lon, limit: 1, at: date) else {
            return nil
        }
        guard let next = upcoming.first else { return "Program încheiat" }
        return next.minutes == 0 ? "Acum" : "În \(next.minutes) min"
    }

    /// First and last weekday departures of a line, for display.
    func scheduleSummary(line: String) -> String? {
        let times = Array((lines[line.uppercased()] ?? [:]).values)
            .flatMap { $0.departures["LV"]?.values.flatMap { $0 } ?? [] }
        guard let first = times.min(), let last = times.max() else { return nil }
        return "primul tren \(Self.clock(first)), ultimul \(Self.clock(last)) (L–V)"
    }

    func facilities(name: String, lat: Double, lon: Double) -> MetroFacilities? {
        guard let sid = stationId(name: name, lat: lat, lon: lon), let record = stations[sid] else { return nil }
        return MetroFacilities(
            entrances: record.entrances.map { $0.name.components(separatedBy: " / ").first ?? $0.name },
            pathways: record.pathways,
            transfers: record.transfers.map(\.name),
            hasRestrooms: record.restrooms
        )
    }

    // MARK: - Matching

    /// Matches by normalized name, preferring the nearest same-named station. Falls back to the
    /// nearest station within 300 m when no name matches.
    private func stationId(name: String, lat: Double, lon: Double) -> String? {
        let named = stationIdsByName[Self.normalize(name)] ?? []
        let candidates = named.isEmpty ? Array(stations.keys) : named

        var best: (id: String, meters: Double)?
        for id in candidates {
            guard let record = stations[id] else { continue }
            let d = Self.meters(record.lat, record.lon, lat, lon)
            if best == nil || d < best!.meters {
                best = (id, d)
            }
        }
        guard let match = best else { return nil }
        if !named.isEmpty { return match.id }
        return match.meters <= 300 ? match.id : nil
    }

    static func normalize(_ value: String) -> String {
        value
            .replacingOccurrences(of: #"\(M\d\)"#, with: "", options: [.regularExpression, .caseInsensitive])
            .folding(options: [.diacriticInsensitive, .caseInsensitive], locale: nil)
            .filter { $0.isLetter || $0.isNumber }
    }

    static func meters(_ lat1: Double, _ lon1: Double, _ lat2: Double, _ lon2: Double) -> Double {
        let dLat = (lat2 - lat1) * 111_000
        let dLon = (lon2 - lon1) * 111_000 * cos(lat1 * .pi / 180)
        return (dLat * dLat + dLon * dLon).squareRoot()
    }

    /// Minutes since midnight (may exceed 1440 for after-midnight trips) to "HH:mm".
    static func clock(_ minutes: Int) -> String {
        String(format: "%02d:%02d", (minutes / 60) % 24, minutes % 60)
    }
}
